#include <winsock2.h>
#include "hivedesk/transport.h"
#include "hivedesk/config.h"
#include <cstdio>
#include <cstdlib>
#include <future>
#include <thread>
#include <chrono>
int self_test(){
    WSADATA data{};if(WSAStartup(MAKEWORD(2,2),&data))return 1;
    SOCKET probe=socket(AF_INET,SOCK_STREAM,IPPROTO_TCP);sockaddr_in address{};address.sin_family=AF_INET;address.sin_addr.s_addr=htonl(INADDR_LOOPBACK);
    int size=sizeof(address);if(bind(probe,reinterpret_cast<sockaddr*>(&address),sizeof(address))||getsockname(probe,reinterpret_cast<sockaddr*>(&address),&size)){closesocket(probe);WSACleanup();return 1;}
    const auto port=ntohs(address.sin_port);closesocket(probe);WSACleanup();
    hive::Transport server,client;std::string error,peer;const auto key=hive::Transport::generate_group_key();
    if(!server.start({"path-server","Path server",key,port,false,true}, {},error)||!client.start({"path-client","Path client",key,0,false,true},{},error)||!client.connect("127.0.0.2",port,peer,error)){std::printf("FAIL setup %s\n",error.c_str());return 1;}
    for(bool udp:{false,true}){
        hive::PathProbeResult result;
        if(!client.measure_path(peer,udp,2000000,1000,result,error)||result.received_packets<150||result.received_packets>result.sent_packets||result.source_elapsed_us<900000){std::printf("FAIL %s %s sent=%llu received=%llu\n",udp?"UDP":"TCP",error.c_str(),result.sent_packets,result.received_packets);return 1;}
        std::printf("PASS generated %s sent=%llu received=%llu bytes=%llu\n",udp?"UDP":"TCP",result.sent_packets,result.received_packets,result.received_bytes);
    }
    hive::PathProbeResult bad;if(client.measure_path(peer,true,1000000000,1000,bad,error)||client.measure_path(peer,false,1000000,60000,bad,error)){std::puts("FAIL unbounded probe accepted");return 1;}
    auto cancelled=std::async(std::launch::async,[&]{hive::PathProbeResult r;std::string e;return client.measure_path(peer,true,2000000,10000,r,e);});
    std::this_thread::sleep_for(std::chrono::milliseconds(100));server.stop();
    if(cancelled.wait_for(std::chrono::seconds(2))!=std::future_status::ready||cancelled.get()){std::puts("FAIL stopped peer did not cancel bounded probe");return 1;}
    client.stop();std::puts("PASS probe bounds and peer-stop cancellation");return 0;
}
int main(int argc,char** argv){
    if(argc==2&&std::string(argv[1])=="--self-test")return self_test();
    if(argc<2){std::puts("Usage: HiveDeskPathCheck <IPv4> [tcp|udp] [Mbps 0.1-20] [seconds 1-10]\nGenerated bytes only. Remote HiveDesk must support path measurements. Exit 0 means measurement completed, not that streaming is usable.");return 2;}
    const bool udp=argc>2&&std::string(argv[2])=="udp";
    const double mbps=argc>3?std::atof(argv[3]):5,seconds=argc>4?std::atof(argv[4]):5;
    if(!(mbps>=0.1&&mbps<=20&&seconds>=1&&seconds<=10))return 2;
    const auto config=hive::load_config();hive::Transport client;std::string error,peer;
    hive::TransportCallbacks callbacks;
    callbacks.peer=[](const hive::Peer& p){if(!p.version.empty())std::printf("peer=%s version=%s\n",p.name.c_str(),p.version.c_str());};
    if(!client.start({"path-check-"+std::to_string(GetCurrentProcessId()),"Generated path measurement",config.group_key,0,false,true},callbacks,error)||
       !client.connect(argv[1],config.port,peer,error)){std::printf("FAIL %s\n",error.c_str());return 1;}
    hive::PathProbeResult r;
    const bool ok=client.measure_path(peer,udp,uint32_t(mbps*1000000),uint32_t(seconds*1000),r,error);client.stop();
    if(!ok){std::printf("FAIL %s\n",error.c_str());return 1;}
    std::printf("MEASURE protocol=%s target_mbps=%.2f sent=%llu received=%llu bytes=%llu source_us=%llu arrival_span_us=%llu delivered_mbps=%.3f missing=%.2f%%\n",
        udp?"udp":"tcp",mbps,r.sent_packets,r.received_packets,r.received_bytes,r.source_elapsed_us,r.receive_span_us,
        r.source_elapsed_us?double(r.received_bytes)*8/r.source_elapsed_us:0.,r.sent_packets?100.*(r.sent_packets-r.received_packets)/r.sent_packets:0.);
    return 0;
}
